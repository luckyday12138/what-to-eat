private fun d(
    name: String,
    slots: Set<Slot>,
    cuisine: String,
    tags: List<String>,
    imageKey: String,
    price: Int = 0,
    spicy: Int = 0,
    heat: Int = 0,
): Dish = Dish(
    id = "",
    name = name,
    slots = slots,
    cuisine = cuisine,
    // 数据源里出现过同一道菜标两次「快手」，进库前就去重，卡片上才不会出现两个一样的标签
    tags = tags.distinct(),
    imageKey = imageKey,
    // 档位一律按买菜成本算，手填的 price 不再参与，避免「¥¥¥ 却只值 18 元」
    priceLevel = PriceTag.level(name, SEED_ING[name] ?: emptyList()),
    spicy = spicy,
    heat = heat,
    origin = Origin.SEED,
    weight = 1f,
    // 有了配料清单，价格才能按买菜成本算，详情页的食材也不再是空的
    ingredients = SEED_ING[name] ?: emptyList(),
)

